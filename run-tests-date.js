//   osascript -l JavaScript run-tests-date.js
// 用 macOS 自带 JXA（JavaScriptCore，与 PopClip 同引擎系）执行，无需安装 Node。
// 「今天」被固定成 2026-08-04（周二），扩展里的 new Date() 由下面的 FakeDate 顶替，
// 因此用例的期望值是死数字；每条用例还会额外做幂等性检查（再跑一遍不应再变）。
ObjC.import('Foundation');
const CWD = ObjC.unwrap($.NSFileManager.defaultManager.currentDirectoryPath);
const EXT = CWD + '/时间标注.popcliptxt';
function readFile(path) {
  return ObjC.unwrap($.NSString.stringWithContentsOfFileEncodingError(path, $.NSUTF8StringEncoding, null));
}

// ---------- 把「今天」钉死 ----------
const RealDate = Date;
let NOW = 0; // 每条用例前设定
function FakeDate(...args) {
  if (!(this instanceof FakeDate)) return RealDate(...args);
  return args.length === 0 ? new RealDate(NOW) : new RealDate(...args);
}
FakeDate.prototype = RealDate.prototype;
FakeDate.now = () => NOW;
FakeDate.parse = RealDate.parse;
FakeDate.UTC = RealDate.UTC;
const at = (y, m, d) => new RealDate(y, m - 1, d, 10, 30, 0).getTime(); // 当天上午，避开边界

// ---------- 载入扩展 ----------
// 扩展是模块格式：给 popclip / module / Date 三个桩执行之，取导出的动作；
// pasteText 截获粘贴结果，showFailure 记为 null（= 没认出任何时间词）。
let pasted = null;
const popclipStub = { pasteText: (t) => { pasted = t; }, showFailure: () => { pasted = null; } };
const moduleStub = { exports: {} };
new Function('popclip', 'module', 'Date', readFile(EXT))(popclipStub, moduleStub, FakeDate);
const ACTION = moduleStub.exports.actions[0];
const DEFAULTS = { format: 'slash', weekday: false, bareWeekday: 'this' };
function fire(text, opts, now) { // 跑一次动作，返回粘贴出去的文本（null = showFailure）
  NOW = now === undefined ? at(2026, 8, 4) : now;
  pasted = null;
  ACTION.code({ text }, Object.assign({}, DEFAULTS, opts || {}));
  return pasted;
}

