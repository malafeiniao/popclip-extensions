let pass = 0, fail = 0;
const lines = [];
function runSuite(label, fn, suite) {
  for (const [name, input, expected] of suite) {
    const got = fn(input);
    const again = fn(got);
    const ok = got === expected, idem = again === got;
    if (ok && idem) { pass++; continue; }
    fail++;
    lines.push(`FAIL [${label}] ${name}`);
    if (!ok) {
      lines.push(`  输入: ${JSON.stringify(input)}`);
      lines.push(`  期望: ${JSON.stringify(expected)}`);
      lines.push(`  实际: ${JSON.stringify(got)}`);
    }
    if (!idem) lines.push(`  不幂等: 第二遍 ${JSON.stringify(again)}`);
  }
}
runSuite('隔', T, cases);
runSuite('标', P, casesPunct);
const total = cases.length + casesPunct.length;
lines.push(`${pass}/${total} 通过（隔 ${cases.length} + 标 ${casesPunct.length}）${fail ? `，${fail} 失败` : ''}`);
function run() { return lines.join('\n'); }
